// worldOf(si): thế giới 0..5 của cửa theo CHỈ SỐ MẢNG si (0-based). Thuần data.
// 0 mặt đất · 1 đại dương · 2 vũ trụ · 3 băng tuyết · 4 cống ngầm · 5 rừng già
export function worldOf(si) {
  const t = ST[si];
  return t.jungle ? 5 : t.sewer ? 4 : t.ice ? 3 : t.space ? 2 : t.water ? 1 : 0;
}
